package ru.derzhus.app

/** Тёплые фразы поддержки. Тон: без давления и осуждения. */
object Praise {
    private val start = listOf(
        "Первые дни самые трудные, и ты уже в пути. Это важнее любых слов.",
        "Каждый час считается. Ты делаешь это прямо сейчас.",
        "Ты выбрал себя. Остальное дело времени.",
        "Тяга приходит волнами и уходит. Просто переждать, ты справляешься."
    )
    private val week = listOf(
        "Организм уже перестраивается. Ты держишься лучше, чем думаешь.",
        "С каждым днём становится чуть легче. Это не обещание, это обычный ход вещей.",
        "Ты уже доказал себе, что можешь. Продолжай в своём темпе.",
        "Привычка слабеет, пока ты не кормишь её. Так держать."
    )
    private val month = listOf(
        "Вот это серия! Ты можешь гордиться собой.",
        "Теперь это уже новый образ жизни, а не героизм через силу.",
        "Посмотри, сколько ты накопил: и дней, и денег. Всё это твоё.",
        "Ты стал примером для самого себя прошлого."
    )
    private val long = listOf(
        "Ты на другом уровне. Это впечатляет по-настоящему.",
        "Такая серия говорит о тебе больше, чем любые обещания.",
        "Свобода от привычки: ты её заслужил каждым днём.",
        "Спокойная уверенность. Так выглядит победа."
    )
    private val support = listOf(
        "Тяга пройдёт. Она всегда проходит, даже если кажется иначе.",
        "Сделай ещё один медленный выдох. Ты сильнее этой минуты.",
        "Выпей воды, пройдись. Через несколько минут будет легче.",
        "Ты уже так далеко зашёл. Не обнуляй это ради пары минут.",
        "Скажи себе: «Не сейчас». Этого достаточно."
    )

    fun daily(h: Habit, now: Long): String {
        val d = Calc.fullDays(h, now)
        val list = when {
            d < 3 -> start
            d < 14 -> week
            d < 100 -> month
            else -> long
        }
        return list[(d + h.id.hashCode()).mod(list.size)]
    }

    fun support(step: Int): String = support[step.mod(support.size)]

    fun relapse(bestDays: Long): String =
        if (bestDays > 0)
            "Это не конец. Срыв случается почти у каждого, а твой рекорд ($bestDays ${Calc.dayWord(bestDays)}) сохранится. Начнём новую серию?"
        else
            "Это не конец. Срыв случается почти у каждого. Начнём новую серию?"
}
